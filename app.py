from decimal import Decimal, InvalidOperation


@app.route("/admin/doctors/add", methods=["GET", "POST"])
@admin_required
def add_doctor():
    if request.method == "POST":
        full_name = request.form.get("full_name", "").strip()
        email = request.form.get("email", "").strip()
        speciality = request.form.get("speciality", "").strip()
        qualifications = request.form.get("qualifications", "").strip()
        biography = request.form.get("biography", "").strip()
        hospital = request.form.get("hospital", "").strip()
        station = request.form.get("station", "").strip()
        department = request.form.get("department", "").strip()
        availability = request.form.get("availability", "").strip()
        salary_text = request.form.get("salary", "").strip()

        if not full_name or not speciality or not email:
            flash("Doctor name, email and speciality are required.", "error")
            return render_template("add_doctor.html")

    salary_text = request.form.get("salary", "").strip()

    salary = None
    if salary_text:
        try:
            salary = Decimal(salary_text)
            if not salary.is_finite() or salary < 0:
                raise InvalidOperation
        except InvalidOperation:
            flash("Please enter a valid non-negative salary.", "error")
            return render_template("add_doctor.html")

        doctor = Doctor(
            full_name=full_name,
            email=email,
            speciality=speciality,
            qualifications=qualifications or None,
            biography=biography or None,
            hospital=hospital or None,
            station=station or None,
            department=department or None,
            salary=salary,
            availability=availability or None,
        )

    try:
        db.session.add(doctor)
        db.session.commit()
        flash("Doctor profile saved successfully.", "success")
        return redirect(url_for("admin"))
    except Exception:
        db.session.rollback()
        app.logger.exception("Could not save doctor profile")
        return render_template("add_doctor.html")


