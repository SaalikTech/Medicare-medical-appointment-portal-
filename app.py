def is_conflict(dr, date, time):
    conflict = db.session.execute(
        db.select(Booking.id)
        .where(
            Booking.dr == dr,
            Booking.date == date,
            Booking.time == time,
        )
        .limit(1)
    ).first()

    return conflict is not None


