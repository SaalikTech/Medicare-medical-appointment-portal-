class User(UserMixin):
    def __init__(self, user_id, email, role):
        self.id = str(user_id)
        self.email = email
        self.role = role


@login_manager.user_loader
def load_user(user_id):
    user = db.session.get(UserModel, int(user_id))

    if user is None:
        return None

    return User(user.id, user.email, user.role)


def admin_required(view_function):
    @wraps(view_function)
    @login_required
    def wrapped_view(*args, **kwargs):
        if current_user.role != "admin":
            abort(403)

        return view_function(*args, **kwargs)

    return wrapped_view


@app.route("/login", methods=["GET", "POST"])
def login():
    if current_user.is_authenticated:
        return redirect(url_for("index"))

    if request.method == "POST":
        email = request.form.get("email", "").strip().lower()
        password = request.form.get("password", "")

        user_record = db.session.execute(
            db.select(UserModel).where(db.func.lower(UserModel.email) == email)
        ).scalar_one_or_none()

        if user_record and check_password_hash(user_record.password_hash, password):
            user = User(
                user_record.id,
                user_record.email,
                user_record.role,
            )
            login_user(user, remember=False, fresh=True)
            return redirect(url_for("index"))

        flash("Invalid email or password.", "error")

    return render_template("login.html")


@app.route("/api/login", methods=["POST"])
def api_login():
    if current_user.is_authenticated:
        return {"message": "Already logged in."}, 200

    data = request.get_json(silent=True) or {}

    email = data.get("email", "").strip().lower()
    password = data.get("password", "")

    if not email or not password:
        return {"error": "Email and password are required."}, 400

    user_record = db.session.execute(
        db.select(UserModel).where(db.func.lower(UserModel.email) == email)
    ).scalar_one_or_none()

    if not user_record or not check_password_hash(user_record.password_hash, password):
        return {"error": "Invalid email or password."}, 401

    user = User(
        user_record.id,
        user_record.email,
        user_record.role,
    )

    login_user(user, remember=False, fresh=True)

    return {
        "message": "Login successful.",
        "role": user_record.role,
    }, 200


